  <h1 class="mt-5">Privasi si kecil, prioritas kita.</h1>
  <h2>Digunakan bersama orang dewasa</h2>
  <p>
    Fokus, Dengar, dan Pikir adalah alat bantu edukasi untuk anak, terutama usia 4–7 tahun. Selalu
    gunakan dengan persetujuan dan pendampingan orang tua atau terapis. Aplikasi ini bukan alat
    diagnosis, ukuran klinis, atau pengganti terapi profesional.
  </p>
  <h2>Apa yang diproses?</h2>
  <p>
    Saat pendamping menyetujui penggunaan mikrofon, suara dikirim langsung ke Google Gemini untuk
    percakapan dan pemahaman jawaban. Data diproses sesuai ketentuan layanan Google Gemini. Pilih
    akun/proyek Google dengan ketentuan pemrosesan data yang sesuai untuk penggunaan anak sebelum
    memakai layanan ini.
  </p>
  <p class="mt-3">
    Aplikasi tidak merekam atau menyimpan audio mentah maupun transkrip percakapan. Hanya nama
    panggilan dalam cerita yang dikirim; email, usia, dan identitas akun tidak dibutuhkan oleh AI.
  </p>
  <h2>Apa yang disimpan?</h2>
  <p>
    Email dan nama akun pendamping, kata sandi yang di-hash, profil anak, pilihan level dan mode,
    sesi, hasil per percobaan, waktu respons, serta penggunaan bantuan. Tidak ada iklan, pelacak
    pihak ketiga, atau profil anak yang dipublikasikan.
  </p>
  <h2>Kendali ada di tangan Anda</h2>
  <p>
    Ubah profil kapan saja melalui pengaturan. Menghapus profil akan menghapus sesi dan semua
    riwayatnya secara permanen. Penilaian AI dapat dikoreksi pada halaman riwayat. Izin mikrofon
    dapat dicabut melalui pengaturan browser. Mikrofon dilepas saat sesi berakhir atau halaman
    ditutup.
  </p>
  <h2>Internet dan penyimpanan offline</h2>
  <p>
    Kerangka aplikasi dan aset statis dapat dibuka offline setelah kunjungan pertama. Halaman
    pribadi dan API tidak di-cache. Percakapan suara dan penyimpanan hasil memerlukan internet;
    aplikasi tidak berpura-pura menjalankan AI saat offline.
  </p>
